export function coverageForModule(moduleId: string): TrainingCoverageRequirement[] {
  return complianceCoverage.filter((requirement) => requirement.moduleIds.includes(moduleId));
}

export function coverageByArea(area: ComplianceArea): TrainingCoverageRequirement[] {
  return complianceCoverage.filter((requirement) => requirement.area === area);
}
